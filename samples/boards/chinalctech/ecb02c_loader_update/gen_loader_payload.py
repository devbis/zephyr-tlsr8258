"""Turn a loader image (zephyr.phy6252.bin, flash offset 0x2000) into a C table of its 4 KB sectors
that hold data. The table of the boot ROM, at the start of the image, is the last one in the
table."""

import struct
import sys

FLASH_OFFSET = 0x2000
SECTOR = 0x1000
FLASH_BASE = 0x11000000
FLASH_END = 0x11040000
RUN_ADDRESS = 0x1FFF1838
SRAM_START = 0x1FFF1840
SRAM_END = 0x20000000


def main(src, dst):
    data = open(src, "rb").read()

    # The sanity checks of the table and of the first vectors, as make_image.py writes them
    count, _, run = struct.unpack_from("<III", data)
    if count != 4 or run != RUN_ADDRESS:
        sys.exit(f"not an image of the boot ROM: {count} records, run address {run:#x}")
    xip = None
    for i in range(count):
        off, size, address, _ = struct.unpack_from("<IIII", data, 0x100 + 16 * i)
        if FLASH_BASE <= address < FLASH_END and xip is None:
            xip = (off, size, address)
    if xip is None:
        sys.exit("no XIP record in the table")
    off, size, address = xip
    sp, reset = struct.unpack_from("<II", data, off - FLASH_OFFSET)
    if (not SRAM_START <= sp <= SRAM_END or not reset & 1 or
            not address <= (reset & ~1) < address + size):
        sys.exit(f"bad vectors: sp={sp:#x} reset={reset:#x}")

    sectors = []
    for pos in range(0, len(data), SECTOR):
        chunk = data[pos:pos + SECTOR]
        if chunk.count(0xFF) != len(chunk):
            sectors.append((FLASH_OFFSET + pos, chunk.ljust(SECTOR, b"\xff")))
    # The table of the boot ROM goes last, a half written loader then has the old table
    sectors.sort(key=lambda s: s[0] == FLASH_OFFSET)

    out = [f"/* Generated by gen_loader_payload.py from {src} */",
           '#include "loader_payload.h"', "",
           "const struct loader_sector loader_sectors[] = {"]
    for offset, chunk in sectors:
        out.append(f"\t{{ {offset:#x}, {{")
        for i in range(0, SECTOR, 16):
            out.append("\t\t" + ", ".join(f"{b:#04x}" for b in chunk[i:i + 16]) + ",")
        out.append("\t} },")
    out += ["};", "", f"const unsigned int loader_sector_count = {len(sectors)};", ""]
    open(dst, "w").write("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: gen_loader_payload.py <loader image> <output.c>")
    main(sys.argv[1], sys.argv[2])
